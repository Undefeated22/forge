-- Phase 1: ingestion & triage.
--
-- Three changes:
--   1. organizations gains a public, non-enumerable ingest slug + a key version
--      so a single tenant's ingest key can be revoked without rotating the
--      master secret for everyone.
--   2. incidents gains entity-level dedup identity (fingerprint) and signal
--      rollup counters, plus a PARTIAL unique index that makes find-or-create
--      atomic — 500 simultaneous signals collapse to one incident, count 500,
--      with no application-level lock.
--   3. signals records every triaged signal, escalated OR suppressed. This is
--      the calibration set: without the suppressed rows there is no way to ever
--      measure FPR/TPR and move the threshold off its hand-set prior.

ALTER TABLE "organizations" ADD COLUMN IF NOT EXISTS "ingest_slug" text;
