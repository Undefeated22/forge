-- At most one OPEN incident per (tenant, fingerprint). The predicate is what
-- makes this a dedup key rather than a permanent one: once an incident is
-- resolved it stops occupying the slot and the same entity can open a new one.
-- fingerprint already includes tenant_id, but the index is explicit about it so
-- a future fingerprint change can't silently create cross-tenant collisions.
CREATE UNIQUE INDEX IF NOT EXISTS "incidents_open_fingerprint_idx"
    ON "incidents" ("tenant_id", "fingerprint") WHERE "status" = 'open';
--> statement-breakpoint

CREATE TABLE IF NOT EXISTS "signals" (
	"id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
	"tenant_id" uuid NOT NULL,
	"incident_id" uuid,
	"source" text,
	"entity" text,
	"fingerprint" text,
	"severity" text,
	-- calibrated anomaly probability and the threshold it was judged against.
	-- Both are stored: tau moves when the cost ratio changes, and a stored score
	-- with a stored tau lets you replay every past decision under a new tau.
	"score" double precision NOT NULL,
	"threshold" double precision NOT NULL,
	"escalated" boolean NOT NULL,
	"features" jsonb,
	-- bounded excerpt only. Suppressed signals must stay cheap: the whole point
	-- of triage is not paying to store or reason about routine noise.
	"excerpt" text,
	"created_at" timestamp with time zone DEFAULT now()
);
--> statement-breakpoint
CREATE INDEX IF NOT EXISTS "signals_tenant_created_idx" ON "signals" ("tenant_id", "created_at");
--> statement-breakpoint
CREATE INDEX IF NOT EXISTS "signals_fingerprint_idx" ON "signals" ("tenant_id", "fingerprint");
